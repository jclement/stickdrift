// Builds dist/client/sdk.d.ts: the host SDK's type declarations as one
// standalone file, served next to /sdk.js. tsc emits host.d.ts and
// protocol.d.ts; the SDK re-exports the whole protocol module, so inlining
// protocol.d.ts in place of the import is exact. The result is then checked
// by compiling a small consumer against it, so a broken bundle fails the
// build instead of a game's editor.
//
//   bun scripts/sdk-dts.ts        (run by `mise run build`, after vite)
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const out = join(root, "dist/client/sdk.d.ts");
const work = mkdtempSync(join(tmpdir(), "sdk-dts-"));
const tsc = join(root, "node_modules/.bin/tsc");
const COMPILER = ["--ignoreConfig", "--target", "ES2022", "--module", "ESNext", "--moduleResolution", "Bundler", "--lib", "ES2022,DOM,DOM.Iterable", "--strict", "--skipLibCheck"];

try {
  execFileSync(tsc, [...COMPILER, "--types", "vite/client", "--declaration", "--emitDeclarationOnly", "--outDir", work, join(root, "src/client/sdk/host.ts")], { stdio: "inherit", cwd: root });
  const protocol = readFileSync(join(work, "shared/protocol.d.ts"), "utf8");
  const host = readFileSync(join(work, "client/sdk/host.d.ts"), "utf8");
  // Drop host.d.ts's references to the protocol module (multi-line imports
  // included); its declarations are inlined above instead.
  const hostBody = host.replace(/^(import|export)\b[^;]*?from\s+["']\.\.\/\.\.\/shared\/protocol["'];\n/gms, "");
  if (/shared\/protocol/.test(hostBody)) throw new Error("sdk-dts: host.d.ts still references the protocol module");
  const banner = `// Type declarations for https://controller.onewheelgeek.net/sdk.js (the
// Controller host SDK). Generated by scripts/sdk-dts.ts; do not edit.
// Use: save next to your code and map the URL to it, e.g. in tsconfig.json
//   "paths": { "https://controller.onewheelgeek.net/sdk.js": ["./sdk.d.ts"] }
`;
  writeFileSync(out, `${banner}\n// ---- Protocol ----\n\n${protocol}\n// ---- Host ----\n\n${hostBody}`);

  // Prove the bundle stands alone and says what games use.
  writeFileSync(join(work, "sdk.d.ts"), readFileSync(out));
  writeFileSync(
    join(work, "consumer.ts"),
    `import { ControllerHost, pressed, held, released, Button, LAYOUTS, type PadPoll, type PadLook, type HostEvents } from "./sdk";
const look: PadLook = { layout: LAYOUTS[0].id, labels: { A: "JUMP" }, theme: { style: "retro" } };
const host = new ControllerHost({ title: "t", look });
host.on("join", (pad, rejoin) => host.setPad(pad.pad, { label: String(rejoin) }));
const on: HostEvents["p2p"] = (pad) => void pad.p2p;
host.on("p2p", on);
const p: PadPoll | undefined = host.poll().get(0);
const ok: boolean = pressed(p, "A") || held(p, "B") || released(p, "Start") || (p?.p2p ?? false) || (p?.rtt ?? 0) > Button.A;
void ok;
`,
  );
  execFileSync(tsc, [...COMPILER, "--noEmit", "--types", "", join(work, "consumer.ts")], { stdio: "inherit", cwd: work });
  console.log(`wrote ${out}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
